"""Generate typed Flutter strings from the reviewed bilingual source catalog."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
messages = json.loads((root / 'lib/l10n/messages.json').read_text(encoding='utf-8'))
keys = set()
def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
lines = ["// Generated by tool/generate_localizations.py. Edit messages.json instead.\n// ignore_for_file: prefer_interpolation_to_compose_strings",
         "import 'package:flutter/foundation.dart';", "import 'package:flutter/widgets.dart';", "",
         "class AppStrings {", "  const AppStrings(this.locale);", "  final Locale locale;",
         "  bool get isEnglish => locale.languageCode != 'zh';",
         "  static const delegate = _StringsDelegate();",
         "  static AppStrings of(BuildContext context) => Localizations.of<AppStrings>(context, AppStrings) ?? const AppStrings(Locale('zh', 'CN'));",
         "  String _format(String value, List<Object?> args) => value.replaceAllMapped(RegExp(r'\\{arg(\\d+)\\}'), (match) => args[int.parse(match[1]!)].toString());",
]
for message in messages:
    key,zh,en = (message[k] for k in ('key','zh','en'))
    assert key not in keys, key
    keys.add(key)
    args = sorted(set(re.findall(r'\{arg(\d+)\}',zh)),key=int)
    assert args == sorted(set(re.findall(r'\{arg(\d+)\}',en)),key=int), key
    if args:
        signature=', '.join('Object? arg'+i for i in args)
        values=', '.join('arg'+i for i in args)
        lines.append(f'  String {key}({signature}) => _format(isEnglish ? {literal(en)} : {literal(zh)}, [{values}]);')
    else: lines.append(f'  String get {key} => isEnglish ? {literal(en)} : {literal(zh)};')
# Late translation is only for application-owned status/error messages, never user data.
lines += ["", "  String message(String value) {", 
          "    for (final item in _lateMessages) {",
          "      final chineseMatch = item.pattern.firstMatch(value);",
          "      final match = chineseMatch ?? item.englishPattern.firstMatch(value);",
          "      if (match != null) {",
          "        final source = chineseMatch == null ? item.english : item.chinese;",
          r"        final indexes = RegExp(r'\{arg(\d+)\}').allMatches(source).map((m) => int.parse(m[1]!)).toList();",
          "        final args = List<Object?>.filled(match.groupCount, '');",
          "        for (var i=0; i<indexes.length; i++) { args[indexes[i]] = message(match[i+1]!); }",
          "        return _format(isEnglish ? item.english : item.chinese, args);",
          "      }",
          "    }", "    return value;", "  }", "}", "",
          "class _LateMessage {", r"  _LateMessage(this.chinese, this.english) : pattern = _pattern(chinese), englishPattern = english.replaceAll(RegExp(r'\{arg\d+\}'), '').trim().isEmpty ? RegExp(r'(?!)') : _pattern(english);",
          r"  static RegExp _pattern(String source) => RegExp('^' + source.split(RegExp(r'\{arg\d+\}')).map(RegExp.escape).join(r'([\s\S]*?)') + r'$');",
          "  final RegExp pattern, englishPattern;", "  final String chinese, english;", "}",
          "final _lateMessages = <_LateMessage>[",
]
for message in sorted(messages,key=lambda x:len(x['zh']),reverse=True):
    lines.append(f"  _LateMessage({literal(message['zh'])}, {literal(message['en'])}),")
lines += [
    "];", "class _StringsDelegate extends LocalizationsDelegate<AppStrings> {", "  const _StringsDelegate();",
    "  @override bool isSupported(Locale locale) => ['zh','en'].contains(locale.languageCode);",
    "  @override Future<AppStrings> load(Locale locale) => SynchronousFuture(AppStrings(locale));",
    "  @override bool shouldReload(_StringsDelegate old) => false;", "}",
    "extension LedgerLocalizedContext on BuildContext { AppStrings get l10n => AppStrings.of(this); }", "",
]
(root / 'lib/l10n/app_strings.dart').write_text('\n'.join(lines),encoding='utf-8')
print(f'Generated {len(messages)} typed bilingual messages')
